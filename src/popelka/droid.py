"""Original astromech-style chirps for a custom voice pack.

R2-D2's real sounds are copyrighted, so this module does **not** sample them.
It synthesises new droid-ish whistles from frequency sweeps, vibrato and a
little noise - same character, no borrowed audio.

Everything is stdlib (``wave``, ``math``, ``random``, ``array``), so it runs in
Termux without numpy or ffmpeg. Convert to the robot's format afterwards with
ffmpeg once the pack inspection tells us what that format is.
"""

from __future__ import annotations

import math
import random
import sys
import wave
from array import array
from pathlib import Path

SAMPLE_RATE = 22050


def _envelope(u: float, attack: float = 0.04, release: float = 0.16) -> float:
    """Cosine attack/release so chirps do not click."""
    if u < attack:
        a = 0.5 - 0.5 * math.cos(math.pi * u / attack)
    else:
        a = 1.0
    if u > 1.0 - release:
        r = 0.5 - 0.5 * math.cos(math.pi * (1.0 - u) / release)
    else:
        r = 1.0
    return a * r


def _tone(duration: float, rng: random.Random, low: bool = False) -> list[float]:
    """One chirp: an exponential sweep with vibrato and a few harmonics."""
    n = max(1, int(duration * SAMPLE_RATE))
    if low:
        f0 = rng.uniform(130.0, 320.0)
        ratio = rng.uniform(0.75, 1.6)
        vib_rate = rng.uniform(8.0, 22.0)
        harmonics = (1.0, 0.55, 0.3)
        noise = rng.uniform(0.05, 0.10)
    else:
        f0 = rng.uniform(430.0, 1750.0)
        ratio = rng.uniform(0.55, 2.7)
        vib_rate = rng.uniform(15.0, 50.0)
        harmonics = rng.choice(((1.0,), (1.0, 0.45), (1.0, 0.4, 0.22)))
        noise = rng.uniform(0.015, 0.05)
    vib_depth = rng.uniform(0.006, 0.045)
    norm = sum(harmonics)

    out: list[float] = []
    phase = 0.0
    for i in range(n):
        u = i / n
        t = i / SAMPLE_RATE
        freq = f0 * (ratio**u)
        freq *= 1.0 + vib_depth * math.sin(2.0 * math.pi * vib_rate * t)
        phase += 2.0 * math.pi * freq / SAMPLE_RATE
        sample = sum(a * math.sin((h + 1) * phase) for h, a in enumerate(harmonics))
        sample = sample / norm + rng.uniform(-noise, noise)
        out.append(sample * _envelope(u))
    return out


def _silence(seconds: float) -> list[float]:
    return [0.0] * max(0, int(seconds * SAMPLE_RATE))


def normalize(samples: list[float], peak: float = 0.85) -> list[float]:
    """Scale to a fixed peak so every clip has a comparable loudness."""
    highest = max((abs(s) for s in samples), default=0.0)
    if highest == 0.0:
        return samples
    return [s * peak / highest for s in samples]


def phrase(seed: int, parts: int | None = None) -> list[float]:
    """Deterministic droid "sentence" of 3-6 chirps for a given seed.

    The same seed always produces the same samples, so a voice pack can be
    regenerated byte-for-byte - important because the robot verifies the MD5.
    """
    rng = random.Random(seed)
    count = parts if parts is not None else rng.randint(3, 6)
    out: list[float] = []
    for index in range(count):
        if index == 0 and rng.random() < 0.35:
            out.extend(_tone(rng.uniform(0.09, 0.18), rng, low=True))
        else:
            out.extend(_tone(rng.uniform(0.055, 0.22), rng))
        out.extend(_silence(rng.uniform(0.012, 0.05)))
    if rng.random() < 0.5:  # a closing rising "question"
        out.extend(_tone(rng.uniform(0.08, 0.16), rng))
    return normalize(out)


def write_wav(path: str | Path, samples: list[float], rate: int = SAMPLE_RATE) -> Path:
    """Write 16-bit mono PCM. Values are clipped, not wrapped."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    pcm = array("h", (int(max(-1.0, min(1.0, s)) * 32767) for s in samples))
    if sys.byteorder == "big":  # WAV is little-endian
        pcm.byteswap()
    with wave.open(str(path), "wb") as fh:
        fh.setnchannels(1)
        fh.setsampwidth(2)
        fh.setframerate(rate)
        fh.writeframes(pcm.tobytes())
    return path


def duration(samples: list[float], rate: int = SAMPLE_RATE) -> float:
    return len(samples) / rate
